def _utc() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _canon(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def _sha(value: Any, *, n: int = 16) -> str:
    return hashlib.sha256(_canon(value).encode("utf-8")).hexdigest()[:n]


def _source_ref(function_name: str) -> dict[str, Any]:
    function = getattr(primitive_groups, function_name)
    _lines, line_number = inspect.getsourcelines(function)
    return {
        "path": SOURCE_PATH,
        "name": function_name,
        "line": line_number,
        "language": "python",
    }


def _mutation_option(spec: dict[str, Any], mutator: str) -> dict[str, Any]:
    return {
        "mutator": mutator,
        "mutator_agent_id": f"mut:deterministic:{mutator}@1",
        "reason": f"Adapt {spec['primitive_id']} without rewriting the source-backed group.",
        "input_edge_before": spec["input_edge"],
        "output_edge_before": spec["output_edge"],
        "target_edge_template": {
            "input": spec["input_edge"],
            "output": spec["output_edge"],
            "mutation": mutator,
        },
        "effect_delta": "preserve_or_declare_adapter_delta",
        "preconditions": [
            "source_ref_exists",
            "visible_edge_declared",
            "unit_tests_pass",
        ],
        "proof_obligations": spec["proof_requirements"],
        "runtime_targets": spec["runtime_targets"],
        "candidate": True,
        "serves_truth": False,
    }


def _tokens(spec: dict[str, Any]) -> list[str]:
    values = [
        spec["primitive_id"],
        spec["kind"],
        spec["title"],
        spec["input_edge"],
        spec["output_edge"],
        spec["core_group_edge"],
        spec["hidden_member_edges"],
        spec["adapter_mutators"],
        spec["proof_requirements"],
    ]
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        text = _canon(value) if isinstance(value, (dict, list)) else str(value)
        chars: list[str] = []
        for char in text.lower():
            if char.isalnum():
                chars.append(char)
            elif chars:
                word = "".join(chars)
                chars.clear()
                if len(word) > 1 and word not in seen:
                    seen.add(word)
                    out.append(word)
        if chars:
            word = "".join(chars)
            if len(word) > 1 and word not in seen:
                seen.add(word)
                out.append(word)
    return out


