#!/usr/bin/env python3
"""scripts.run_primitive_generation_campaign — run a bounded, candidate-only primitive-generation CAMPAIGN over
real-world/esoteric technology-stack situations, drafting through the provider-agnostic router.

Flow (primitive_campaigns/esoteric_technology_stack_campaign.yaml is the default campaign):

    real_world_situation_primitive_specs.sample_specs   # deterministic coprime sample across the messy grid
      -> filter to the campaign families + D0/D1 no-side-effect determinism
      -> executor-enqueue ONLY specs with schema + promotable determinism (fixture-provable)
      -> spec_to_executor_synthesizer.run(chat_fn = llm_capability_router.call(draft_job_type))   # Hy3 primary
           + code fallback, quota-gated, ledgered)                                                 # + code fallback
      -> security gate -> SANDBOX-execute against fixtures -> determinism check -> promote candidate->validated
      -> candidate-only campaign report

The LLM PROPOSES (drafts a body + fixtures); the deterministic system DISPOSES (gate + sandbox + promotion).
Non-executor-ready specs are kept as candidate specs (lossless). Every row candidate=true, serves_truth=false.

    python3 scripts/run_primitive_generation_campaign.py --self-test              # offline, stub router lane
    python3 scripts/run_primitive_generation_campaign.py --run --max-jobs 10      # live, Hy3-drafted
    python3 scripts/run_primitive_generation_campaign.py --run --max-jobs 25 --start 25 --dry-run
"""
