#!/usr/bin/env python3
"""scripts.path_router_zoo — ROUTER METHODOLOGIES: choose the graph CONFIG per QUERY instead of one global
champion (the measured finding behind this: always-union LOSES to racing+picking, and different query classes
have different winners). A ZOO of contract-substitutable routers behind one selector, raced by receipt:

  * global_champion   — graph_autotune.active_config() for every query (the incumbent; REUSED, not rebuilt)
  * always_union      — the full multi-path union config (the known loser; kept as the labelled baseline)
  * query_type_rules  — deterministic table keyed by the analyze stage's query_type
  * difficulty_gate   — cheap config for easy queries, escalating machinery as QPP difficulty rises
  * learned_table     — PER-CLASS champions learned by racing (path_graph_bench.quality_bench per class) and
                        persisted (dist/path-router/learned_table.json) — the contextual-router evolution of
                        graph_autotune from "one champion" to "champion per query class"; self-heals to the
                        global champion for unseen classes.

The query CLASS is deterministic: the graph's own analyze options (query_type × difficulty), so routing costs
one 0-token analyze pass. Adding a router = a new ROUTERS row, never a rewrite; a bandit/learned-model router
plugs in as another row behind the same contract (query -> config).

serves_truth=false — routed configs and race receipts are measurements/candidates, never served truth.

    PYTHONPATH=. python3 scripts/path_router_zoo.py --self-test
    PYTHONPATH=. python3 scripts/path_router_zoo.py --race [--sample 200]   # race routers, persist the table
"""
