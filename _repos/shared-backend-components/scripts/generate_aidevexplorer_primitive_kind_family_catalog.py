def generate_rows() -> list[dict[str, Any]]:
    return sorted(PRIMITIVE_KIND_FAMILIES, key=lambda row: str(row["primitive_kind"]))


def write_rows(rows: list[dict[str, Any]]) -> dict[str, Any]:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(
        "".join(json.dumps(row, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n" for row in rows),
        encoding="utf-8",
    )
    by_domain: dict[str, int] = {}
    for row in rows:
        for domain in row.get("domains") or []:
            by_domain[str(domain)] = by_domain.get(str(domain), 0) + 1
    manifest = {
        "record_type": "aidevexplorer_primitive_kind_family_catalog_manifest",
        "path": AIDEVEXPLORER_PRIMITIVE_KIND_FAMILY_CATALOG_PATH,
        "row_count": len(rows),
        "primitive_kinds": [row["primitive_kind"] for row in rows],
        "domain_counts": dict(sorted(by_domain.items())),
        "source_family": AIDEVEXPLORER_PRIMITIVE_KIND_SOURCE_FAMILY,
        "source_evidence_status": AIDEVEXPLORER_PRIMITIVE_KIND_SOURCE_EVIDENCE_STATUS,
        "candidate": True,
        "serves_truth": False,
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-only", action="store_true")
    args = parser.parse_args(argv)
    rows = generate_rows()
    manifest: dict[str, Any] = {
        "row_count": len(rows),
        "would_write": AIDEVEXPLORER_PRIMITIVE_KIND_FAMILY_CATALOG_PATH,
        "candidate": True,
        "serves_truth": False,
    }
    if not args.check_only:
        manifest = write_rows(rows)
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
