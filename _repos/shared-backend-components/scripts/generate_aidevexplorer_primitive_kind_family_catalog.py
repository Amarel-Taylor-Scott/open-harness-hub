def _sha(value: Any, *, n: int = 16) -> str:
    text = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:n]


def _slug(value: str) -> str:
    out = []
    prev_dash = False
    for char in value.lower():
        if char.isalnum():
            out.append(char)
            prev_dash = False
        elif not prev_dash:
            out.append("-")
            prev_dash = True
    return "".join(out).strip("-") or "primitive-kind"


def _family(
    primitive_kind: str,
    title: str,
    *,
    visible_edge: tuple[str, str],
    hidden_edges: list[str],
    effects: list[str],
    mutators: list[str],
    proofs: list[str],
    pitfalls: list[str],
    domains: list[str],
    runtime_targets: list[str],
    examples: list[str],
) -> dict[str, Any]:
    input_edge, output_edge = visible_edge
    return {
        "id": f"pkf:{primitive_kind}:{_sha([primitive_kind, input_edge, output_edge], n=8)}",
        "slug": _slug(primitive_kind),
        "primitive_kind": primitive_kind,
        "title": title,
        "input_edge": input_edge,
        "output_edge": output_edge,
        "visible_edge": f"{input_edge} -> {output_edge}",
        "hidden_member_edges": hidden_edges,
        "effects": effects,
        "adapter_mutators": mutators,
        "proof_requirements": sorted(dict.fromkeys([*proofs, "candidate_boundary_gate"])),
        "common_pitfalls": pitfalls,
        "domains": domains,
        "runtime_targets": runtime_targets,
        "example_tasks": examples,
        "source_family": AIDEVEXPLORER_PRIMITIVE_KIND_SOURCE_FAMILY,
        "source_evidence_status": AIDEVEXPLORER_PRIMITIVE_KIND_SOURCE_EVIDENCE_STATUS,
        "trust": "candidate",
        "candidate": True,
        "serves_truth": False,
    }


