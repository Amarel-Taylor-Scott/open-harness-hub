# ---------------------------------------------------------------- topology load + join

def load_topology(topology_path: Path = TOPOLOGY_PATH,
                  registry_path: Path = SERVICE_REGISTRY_PATH) -> dict:
    topo = json.loads(topology_path.read_text(encoding="utf-8"))
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    ports = {svc["service_id"]: svc["port"] for svc in registry["services"]}
    for svc in topo["services"]:
        rid = svc.get("registry_service_id")
        if rid is not None:
            if rid not in ports:
                raise SystemExit(f"deploy_topology: service '{svc['name']}' references unknown "
                                 f"registry_service_id '{rid}' (not in {registry_path.name})")
            svc["port"] = ports[rid]
        elif svc.get("kind") in ("backend", "web", "data") and "port" not in svc:
            raise SystemExit(f"deploy_topology: service '{svc['name']}' has neither "
                             f"registry_service_id nor an explicit port")
    scaling = next(s for s in topo["services"] if s["name"] == "worker")["scaling"]
    if scaling["queue_key"] != DEFAULT_QUEUE_KEY:
        raise SystemExit(f"deploy_topology: worker scaling.queue_key={scaling['queue_key']!r} but "
                         f"scripts.foundry.queues.DEFAULT_QUEUE_KEY={DEFAULT_QUEUE_KEY!r} — one source only")
    return topo


def fly_app_name(topo: dict, service_name: str) -> str:
    return f"{topo['fly']['app_prefix']}-{service_name}"


def volume_name(svc: dict) -> str:
    """The volume name for a stateful service — ONE definition (toml mounts, volume-create
    steps, and the snapshot-retention runbook must never drift apart)."""
    return re.sub(r"[^a-z0-9_]", "_", f"{svc['name']}_state")


def stateful_services(topo: dict) -> list[dict]:
    """Services owning single-writer volume state (the single-machine-law set), topology order."""
    return [s for s in topo["services"] if s.get("state_mount")]


def resolve_ref(topo: dict, value: str, provider: str) -> str:
    """'@<service>' → that service's base URL on the given provider's private network."""
    if not value.startswith("@"):
        return value
    ref = value[1:]
    if ref.startswith("app:"):  # '@app:worker' → the provider-level app name
        return fly_app_name(topo, ref[4:]) if provider == "fly" else ref[4:]
    target = next((s for s in topo["services"] if s["name"] == ref), None)
    if target is None:
        raise SystemExit(f"deploy_topology: env reference '@{ref}' matches no service")
    if provider == "fly":
        suffix = topo["fly"]["internal_domain_suffix"]
        return f"http://{fly_app_name(topo, ref)}{suffix}:{target['port']}"
    return f"http://{ref}:{target['port']}"  # k8s Service / compose service DNS


def service_env(topo: dict, svc: dict, provider: str) -> dict[str, str]:
    env = {"OH_BIND_HOST": "0.0.0.0"}
    for key, value in (svc.get("env") or {}).items():
        env[key] = resolve_ref(topo, value, provider)
    return env


def secret_keys(topo: dict, svc: dict) -> list[str]:
    keys: list[str] = []
    for group in svc.get("secret_groups") or []:
        keys.extend(topo["secret_group_contents"][group])
    return keys


# ---------------------------------------------------------------- fly emitter

def fly_toml(topo: dict, svc: dict) -> str:
    app = fly_app_name(topo, svc["name"])
    lines = [
        f"# {GENERATED_MARK}",
        f"# service: {svc['name']} (kind={svc['kind']})" + (f" — {svc['phase']}" if svc.get("phase") else ""),
        f'app = "{app}"',
        f'primary_region = "{topo["fly"]["primary_region"]}"',
        "",
        "[build]",
    ]
    if svc.get("image"):
        lines.append(f'  image = "{svc["image"]}"')
    else:
        lines.append(f'  dockerfile = "{topo["image"]["dockerfile"]}"  # deploy from repo root: fly deploy -c fly/{app}.fly.toml')
    lines += ["", "[processes]", f'  app = "{" ".join(svc["command"])}"'] if svc.get("command") else []
    env = service_env(topo, svc, "fly")
    if env:
        lines += ["", "[env]"]
        lines += [f'  {k} = "{v}"' for k, v in sorted(env.items())]
    secrets = secret_keys(topo, svc)
    if secrets:
        lines += ["", f"# secrets (never in this file): fly secrets set -a {app} " + " ".join(f"{k}=…" for k in secrets)]
    if svc.get("state_mount"):
        lines += ["", "[[mounts]]", f'  source = "{volume_name(svc)}"', f'  destination = "{svc["state_mount"]}"',
                  f'  initial_size = "{svc.get("volume_gb", 1)}gb"']
    if svc.get("public"):
        lines += ["", "[http_service]", f"  internal_port = {svc['port']}", "  force_https = true",
                  '  auto_stop_machines = "stop"', "  auto_start_machines = true", "  min_machines_running = 1",
                  "", "  [[http_service.checks]]", '    interval = "30s"', '    timeout = "5s"',
                  '    grace_period = "20s"', '    method = "GET"', f'    path = "{svc.get("health_path", "/")}"']
    elif svc.get("health_path") and svc.get("port"):
        lines += ["", "[checks.health]", '  type = "http"', f"  port = {svc['port']}",
                  f'  path = "{svc["health_path"]}"', '  interval = "30s"', '  timeout = "5s"',
                  '  grace_period = "20s"']
    if svc["kind"] == "burst":
        scaling = svc["scaling"]
        lines += ["", f"# burst fleet: machines are managed by the worker-controller (scale "
                      f"{scaling['min_workers']}→{scaling['max_workers']['fly']} on redis list "
                      f"'{scaling['queue_key']}', {scaling['jobs_per_worker']} jobs/worker). "
                      f"After 'fly deploy --ha=false', stop the seed machine; the controller owns the fleet."]
    lines += ["", "[[vm]]", f'  cpu_kind = "{svc.get("cpu_kind", "shared")}"', f"  cpus = {svc.get('cpus', 1)}",
              f"  memory_mb = {svc.get('memory_mb', 512)}", ""]
    return "\n".join(lines)


