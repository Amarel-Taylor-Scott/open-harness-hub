# ---------------------------------------------------------------- compose emitter

def _compose_services(topo: dict) -> list[dict]:
    """Compose-eligible services (fly-only roles like the worker-controller have no compose analog)."""
    return [s for s in topo["services"]
            if not (s.get("providers") and set(s["providers"]) == {"fly"})]


def _dep_graph(topo: dict) -> dict[str, list[str]]:
    """service → the compose services it references via '@<service>' env refs (sorted, deterministic)."""
    names = {s["name"] for s in _compose_services(topo)}
    graph: dict[str, list[str]] = {}
    for s in _compose_services(topo):
        deps = {v[1:] for v in (s.get("env") or {}).values()
                if isinstance(v, str) and v.startswith("@") and not v.startswith("@app:")}
        graph[s["name"]] = sorted(d for d in deps if d in names)
    return graph


def _acyclic_deps(graph: dict[str, list[str]]) -> tuple[dict[str, list[str]], list[tuple[str, str]]]:
    """Break dependency cycles so docker-compose accepts the graph (it rejects ANY cyclic depends_on).

    compose `depends_on` is start-ORDER only. The env @-refs that can form a cycle here are RUNTIME
    seams — e.g. identity pushes verify-mail to mailbox (best-effort, swallowed) while mailbox calls
    identity to complete an on-demand verify click — so neither is a startup requirement and the
    cycle-closing edge is safe to drop. Deterministic DFS back-edge removal over sorted nodes/edges,
    so the same topology always drops the same edge. Returns (kept_deps, dropped_edges)."""
    WHITE, GRAY, BLACK = 0, 1, 2
    color = {n: WHITE for n in graph}
    kept: dict[str, list[str]] = {n: [] for n in graph}
    dropped: list[tuple[str, str]] = []

    def visit(u: str) -> None:
        color[u] = GRAY
        for v in graph.get(u, []):
            if color.get(v) == GRAY:          # back-edge → closes a cycle → drop it
                dropped.append((u, v))
                continue
            kept[u].append(v)
            if color.get(v) == WHITE:
                visit(v)
        color[u] = BLACK

    for n in sorted(graph):
        if color[n] == WHITE:
            visit(n)
    return kept, dropped


def _compose_has_cycle(compose_text: str) -> bool:
    """Independently parse the EMITTED compose's depends_on edges and report whether they cycle.
    docker-compose rejects ANY cyclic depends_on, so this is the gate that catches a cycle BEFORE
    deploy even if _acyclic_deps ever regresses — defense-in-depth for the exact bug that only
    container start-up (not --check/preflight) first surfaced."""
    graph: dict[str, list[str]] = {}
    cur = None
    in_services = False
    for line in compose_text.splitlines():
        if re.match(r"^services:\s*$", line):
            in_services = True; continue
        if re.match(r"^[A-Za-z]", line):       # a new top-level key (volumes:, name:) ends services
            in_services = False; continue
        if not in_services:
            continue
        m = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
        if m:
            cur = m.group(1); graph.setdefault(cur, [])
            continue
        m = re.match(r"^    depends_on:\s*(\[.*\])\s*$", line)
        if m and cur:
            try:
                graph[cur] = list(json.loads(m.group(1)))
            except (ValueError, TypeError):
                graph[cur] = []
    WHITE, GRAY, BLACK = 0, 1, 2
    color = {n: WHITE for n in graph}

    def walk(u: str) -> bool:
        color[u] = GRAY
        for v in graph.get(u, []):
            if v not in color:        # edge to a non-service (shouldn't happen) — ignore
                continue
            if color[v] == GRAY or (color[v] == WHITE and walk(v)):
                return True
        color[u] = BLACK
        return False

    return any(color[n] == WHITE and walk(n) for n in sorted(graph))


def compose_yaml(topo: dict) -> str:
    """The same plane as plain docker-compose — parity proof and the any-VPS escape hatch."""
    dep_map, dropped_edges = _acyclic_deps(_dep_graph(topo))
    lines = [f"# {GENERATED_MARK}",
             "# Run from repo root: docker compose -f deploy/docker-compose.deploy.yml up",
             "# Worker fleet: --profile workers (scaled manually here; KEDA on k8s / controller on Fly)."]
    for (u, v) in dropped_edges:  # surfaced, never silent: the cycle-closing start-order hint we dropped
        lines.append(f"# depends_on {u}→{v} omitted: runtime seam (best-effort/on-demand) that would "
                     "form a start-order cycle; compose depends_on is ordering only.")
    lines += ["name: aidoneright", "services:"]
    volumes: list[str] = []
    for svc in topo["services"]:
        if svc.get("providers") and set(svc["providers"]) == {"fly"}:
            continue  # fly-only roles (worker-controller) have no compose analog
        lines.append(f"  {svc['name']}:")
        if svc.get("image"):
            lines.append(f"    image: {svc['image']}")
        else:
            lines.append("    build: { context: .., dockerfile: Dockerfile }")
        if svc.get("command"):
            lines.append("    command: " + json.dumps(svc["command"]))
        env = service_env(topo, svc, "compose")
        for group in svc.get("secret_groups") or []:
            if group in ("queue-stores", "baltor-stores"):
                env.setdefault("REDIS_URL", "redis://redis:6379/0")
        if svc["name"] == "postgres":
            env.setdefault("POSTGRES_PASSWORD", "${POSTGRES_PASSWORD:?set in .env}")
        if env:
            lines.append("    environment:")
            lines += [f"      {k}: {json.dumps(v)}" for k, v in sorted(env.items())]
        if svc.get("public"):
            lines.append(f'    ports: ["{svc["port"]}:{svc["port"]}"]')
        if svc.get("state_mount"):
            volume = volume_name(svc)
            volumes.append(volume)
            lines.append(f"    volumes: [{volume}:{svc['state_mount']}]")
        deps = list(dep_map.get(svc["name"], []))  # cycle-broken (see _acyclic_deps)
        if svc["kind"] == "burst":
            deps = sorted(set(deps) | {"redis"})
            lines.append("    profiles: [workers]")
        if svc.get("phase"):
            lines.append("    profiles: [phase2]")
        if deps:
            lines.append("    depends_on: " + json.dumps(deps))
        lines.append("    restart: unless-stopped")
    lines.append("volumes:")
    lines += [f"  {v}:" for v in sorted(set(volumes))]
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- opentofu emitter (cloudflare plane)

def _tf_name(name: str) -> str:
    """A valid OpenTofu/HCL resource label from a service name (deterministic)."""
    return re.sub(r"[^a-z0-9_]", "_", name.lower())


def tofu_main_tf(topo: dict) -> str:
    """Cloudflare provisioning rendered from the SAME topology as fly/ + compose (the doc's 'add an emitter here').

    Emits exactly the two Cloudflare things this topology implies and the Fly runbook otherwise leaves MANUAL:
      * a proxied CNAME per PUBLIC service  (the 'point Cloudflare DNS at the public apps' step), and
      * one R2 bucket per stateful service  (the off-provider state backup the runbook recommends).
    Inert until `tofu apply`; `tofu plan` is the reviewable gate. The token is a SecretRef (TF_VAR_*), never committed."""
    domain_default = topo["fly"].get("public_domain_suffix", "fly.dev")
    public = [s for s in topo["services"] if s.get("public")]
    stateful = stateful_services(topo)
    lines = [
        f"# {GENERATED_MARK}",
        "# Cloudflare plane rendered from architecture/deploy_topology.json — the SAME single source as fly/ + compose",
        "# (no magic values). Provisioning ONLY (DNS + R2); per-request compute stays in the dispatch layer. Inert",
        "# until `tofu apply`; run `tofu plan` first as the gate. Switch/extend providers = add another emitter, never",
        "# a second source of truth.", "",
        "terraform {",
        '  required_version = ">= 1.6"  # OpenTofu',
        "  required_providers {",
        '    cloudflare = { source = "cloudflare/cloudflare", version = "~> 5" }',
        "  }",
        "  # Remote state on R2 (uncomment AFTER a state bucket exists; S3-compatible creds via env):",
        '  # backend "s3" { /* R2 endpoint + bucket; see README.generated.md */ }',
        "}", "",
        'provider "cloudflare" {',
        "  api_token = var.cloudflare_api_token",
        "}", "",
        "# ---- inputs (set via TF_VAR_* env or a gitignored *.tfvars — the token is a SecretRef, never committed) ----",
        'variable "cloudflare_api_token" {',
        "  type        = string",
        "  sensitive   = true",
        '  description = "Cloudflare API token (Zone:DNS:Edit + Workers R2 Storage:Edit). Set TF_VAR_cloudflare_api_token."',
        "}",
        'variable "account_id" {',
        "  type        = string",
        '  description = "Cloudflare account id"',
        "}",
        'variable "zone_id" {',
        "  type        = string",
        '  description = "Cloudflare DNS zone id for the public domain"',
        "}",
        'variable "fly_app_domain" {',
        "  type        = string",
        f'  default     = "{domain_default}"',
        '  description = "CNAME target suffix; a public app routes to <app>.<domain>"',
        "}", "",
        "# ---- public surfaces: a proxied CNAME per public service (the DNS step the Fly runbook leaves manual) ----",
    ]
    for s in public:
        app = fly_app_name(topo, s["name"])
        rn = _tf_name(s["name"])
        lines += [f'resource "cloudflare_dns_record" "{rn}" {{',
                  "  zone_id = var.zone_id",
                  f'  name    = "{s["name"]}"',
                  '  type    = "CNAME"',
                  f'  content = "{app}.${{var.fly_app_domain}}"',
                  "  proxied = true",
                  "  ttl     = 1  # automatic (required when proxied)",
                  "}", ""]
    if not public:
        lines += ['# (no public services in the topology yet — mark one with "public": true)', ""]
    lines += ["# ---- off-provider state backup: one R2 bucket per single-writer stateful service ----"]
    for s in stateful:
        app = fly_app_name(topo, s["name"])
        rn = _tf_name(s["name"])
        lines += [f'resource "cloudflare_r2_bucket" "{rn}_state_backup" {{',
                  "  account_id = var.account_id",
                  f'  name       = "{app}-state-backup"',
                  "}", ""]
    lines += ['output "public_hostnames" {',
              "  value = {",
              *[f'    {_tf_name(s["name"])} = cloudflare_dns_record.{_tf_name(s["name"])}.name' for s in public],
              "  }",
              "}", ""]
    return "\n".join(lines)


