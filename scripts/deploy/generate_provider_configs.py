#!/usr/bin/env python3
"""Provider-config generator — one topology, many providers (the switch-cost killer).

`architecture/deploy_topology.json` is the single source for the cloud service plane
(services, commands, resources, seams, scaling). This script renders it into:

  * `fly/<app>.fly.toml`            — one Fly app per service (current target provider)
  * `fly/README.generated.md`       — exact deploy order + commands (no secrets, placeholders)
  * `deploy/docker-compose.deploy.yml` — the same plane on plain Docker (parity proof + any-VPS path)

and CROSS-CHECKS the hand-maintained K8s manifests (`infra/k8s/service-plane.yaml`,
`infra/k8s/worker.yaml`) against the same topology, so KEDA scaling numbers and the Fly
worker-controller numbers can never drift apart. Ports are never typed in the topology —
they are joined from `architecture/local_service_registry.json` (no magic values).

Switching providers later = add an emitter here (or run the compose file on any VPS/k3s);
the services themselves are provider-blind: they read OH_BIND_HOST, OH_SEAM_*_BASE and
AIDR_IDENTITY_BASE from env, defaulting to the local 127.0.0.1 plane.

Modes:
  python3 scripts/deploy/generate_provider_configs.py              # (re)generate
  python3 scripts/deploy/generate_provider_configs.py --check      # fail if outputs drift / k8s mismatch
  python3 scripts/deploy/generate_provider_configs.py --self-test  # offline invariants
"""
