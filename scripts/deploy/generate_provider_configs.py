def self_test() -> int:
    topo = load_topology()
    rendered = render_all(topo)
    web = rendered[FLY_DIR / f"{fly_app_name(topo, 'web-harness-hub')}.fly.toml"]
    identity = rendered[FLY_DIR / f"{fly_app_name(topo, 'identity')}.fly.toml"]
    worker = rendered[FLY_DIR / f"{fly_app_name(topo, 'worker')}.fly.toml"]
    compose = rendered[COMPOSE_PATH]
    readme = rendered[FLY_DIR / "README.generated.md"]
    tofu = rendered[TOFU_DIR / "main.tf"]
    stateful = stateful_services(topo)
    checks = [
        ("web app is public", "[http_service]" in web and "min_machines_running = 1" in web),
        ("web seams resolve to fly .internal bases",
         'OH_SEAM_IDENTITY_BASE = "http://aidr-identity.internal:9410"' in web
         and 'OH_SEAM_LIVEOPS_BASE = "http://aidr-baltor-backend.internal:9301"' in web),
        ("internal service has no public proxy", "[http_service]" not in identity and "[checks.health]" in identity),
        ("every service binds 0.0.0.0 in containers", all('OH_BIND_HOST = "0.0.0.0"' in t
         for p, t in rendered.items() if p.suffix == ".toml" and "[processes]" in t)),
        ("worker has no proxy and no checks (controller-managed)",
         "[http_service]" not in worker and "[checks.health]" not in worker),
        ("controller is fly-only (absent from compose)", "worker-controller" not in compose),
        ("compose seams resolve to service DNS", '"http://identity:9410"' in compose),
        ("compose wires worker REDIS_URL to the redis service", '"redis://redis:6379/0"' in compose),
        ("generated compose has NO dependency cycle (compose rejects cycles — the deploy-blocker "
         "only container start-up first caught)", not _compose_has_cycle(compose)),
        ("...and the cycle detector actually fires on a planted cycle (not a silent no-op)",
         _compose_has_cycle('services:\n  a:\n    depends_on: ["b"]\n  b:\n    depends_on: ["a"]\n')),
        ("no secret VALUES leak into any generated file", all(
            tok not in content for content in rendered.values()
            for tok in ("sk-or-", "OH_LLM_API_KEY ="))),
        ("k8s cross-checks pass on the real manifests", not check_k8s(topo)),
        ("queue key single-sourced", topo and DEFAULT_QUEUE_KEY == "ohh:foundry:jobs"),
        ("README: scheduled feeder uses the REAL seeds/freshness CLI flags",
         f'--schedule {FEEDER_SCHEDULE} -a {fly_app_name(topo, "worker")} --command '
         f'"python -m scripts.foundry.seeds --enqueue"' in readme
         and '--command "python -m scripts.ingest.freshness --check --enqueue"' in readme),
        ("README: single-machine law names every stateful app",
         "`fly scale count >1`" in readme
         and all(f"`{fly_app_name(topo, s['name'])}` — single-writer state" in readme for s in stateful)),
        ("README: one snapshot-retention line per stateful volume + off-provider backup note",
         readme.count("--snapshot-retention") == len(stateful)
         and f"--snapshot-retention {VOLUME_SNAPSHOT_RETENTION_DAYS}" in readme and "restic" in readme),
        # OPENTOFU emitter (cloudflare) — same single source, one more provider, no lock-in
        ("tofu: cloudflare provider pinned + OpenTofu version floor", 'source = "cloudflare/cloudflare"' in tofu and 'required_version = ">= 1.6"' in tofu),
        ("tofu: a proxied CNAME per public service -> the fly app domain (one source)",
         all((f'resource "cloudflare_dns_record" "{_tf_name(s["name"])}"' in tofu and "proxied = true" in tofu
              and f'content = "{fly_app_name(topo, s["name"])}.${{var.fly_app_domain}}"' in tofu)
             for s in topo["services"] if s.get("public"))),
        ("tofu: an R2 backup bucket per stateful service",
         all(f'name       = "{fly_app_name(topo, s["name"])}-state-backup"' in tofu for s in stateful)),
        ("tofu: the API token is a sensitive SecretRef var (never inlined)", "sensitive   = true" in tofu and "var.cloudflare_api_token" in tofu),
        ("tofu: provisioning only — no per-request compute leaks into IaC", "dispatch layer" in rendered[TOFU_DIR / "README.generated.md"]),
    ]
    # drift detection actually fires
    with tempfile.TemporaryDirectory() as tmp:
        sample = Path(tmp) / "sample.toml"
        sample.write_text(web + "\n# tampered", encoding="utf-8")
        checks.append(("tampered output differs from render", sample.read_text(encoding="utf-8") != web))
    failed = [name for name, ok in checks if not ok]
    for name, ok in checks:
        print(f"  [{'ok' if ok else 'FAIL'}] {name}")
    print(("PASS — " if not failed else "FAIL — ") + f"{len(checks) - len(failed)}/{len(checks)} self-test checks")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify generated files + k8s match the topology")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    if args.check:
        return check()
    return generate()


if __name__ == "__main__":
    raise SystemExit(main())
