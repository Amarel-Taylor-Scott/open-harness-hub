"""scripts.port_full_design_to_web — deterministic transplant of the FULL-DESIGN bundle into the
three wired product front-ends, per the design contract (transplant, don't translate).

Source (the spec, final fidelity):   dist/sites/openharness-design/
Targets (the wired apps):            web/context-is-everything/ · web/baltor/ · web/harness-hub/

What it does, per app:
  * kit/   — every `shared/<file>` the app's pages load is copied BYTE-VERBATIM
             (DESIGN-CONTRACT Rule 0; the --check mode diffs them against the bundle).
  * site code (jsx/js/css) — copied verbatim EXCEPT the explicitly recorded live-data seam
    patches below (PATCHES), which swap fixture data for real backend data with an honest
    fallback. A patch that no longer matches FAILS LOUDLY (the bundle moved → re-record).
  * HTML pages — copied with exactly three mechanical rewrites (everything else verbatim):
      1. `../shared/…` asset paths → `kit/…` (each app stays independently shippable);
      2. pinned unpkg React/Babel `<script>` tags → the local `/vendor/…` runtime;
      3. a same-origin service-seam config script is injected so the kit's identity /
         registry / analytics clients hit this origin (scripts/showcase/server.py proxies).
    Cross-surface `../<sibling>/…` links are NOT rewritten — the showcase server mounts the
    bundle's top-level folders at the origin root, so the verbatim links resolve.
  * the entry prototype HTML becomes index.html; a pre-existing, non-generated index.html is
    preserved as legacy.html (lossless — the old front-end stays reachable, never deleted).
  * a manifest (.design-port-manifest.json) records every generated file for --check.

Modes:
  (no args)     port the bundle into web/ (idempotent)
  --check       regenerate in memory and diff against web/ — exit 1 on ANY drift
  --self-test   port into a temp dir and assert the invariants

Offline, stdlib-only.
"""
