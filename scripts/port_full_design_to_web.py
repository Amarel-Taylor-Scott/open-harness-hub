def _rewrite_html(text: str, src_rel: str, app: str, is_entry: bool, cfg: dict) -> str:
    """The three mechanical rewrites + marker. Everything else stays verbatim."""
    for pattern, repl in _VENDOR_REWRITES:
        text = pattern.sub(repl, text)
    text = text.replace("../shared/", "kit/")
    for old, new in cfg.get("self_link_rewrites", []):
        if not is_entry:
            text = text.replace(f'href="{old}"', f'href="{new}"')
    # seam config before the first script so the kit clients see the overrides at load
    first_script = text.find("<script")
    if first_script != -1:
        text = text[:first_script] + _SEAM_SCRIPT + "\n" + text[first_script:]
    if is_entry:
        for extra in EXTRA_ENTRY_SCRIPTS.get(app, []):
            anchor = '<script src="kit/oh-experiments.js"></script>'
            if anchor not in text:
                raise SystemExit(f"FATAL: {src_rel}: anchor for extra script {extra!r} not found")
            text = text.replace(anchor, anchor + f'\n<script src="{extra}"></script>', 1)
    marker = _MARKER.format(src=src_rel)
    if "<!doctype html>" in text:
        text = text.replace("<!doctype html>", "<!doctype html>\n" + marker, 1)
    else:
        text = marker + "\n" + text
    return text


def _apply_patches(text: str, app: str, name: str) -> str:
    for old, new in PATCHES.get(app, {}).get(name, []):
        if text.count(old) != 1:
            raise SystemExit(
                f"FATAL: recorded patch no longer matches exactly once in {app}/{name} "
                f"(found {text.count(old)}). The bundle moved — re-record the patch.\n--- old:\n{old}"
            )
        text = text.replace(old, new)
    return text


def generate(app: str) -> dict[str, str]:
    """All generated files for one app as {relative_path: content} (no disk writes)."""
    cfg = APPS[app]
    src_dir = BUNDLE / cfg["folder"]
    out: dict[str, str] = {}

    html_names = (sorted(p.name for p in src_dir.glob(cfg["html"])) if isinstance(cfg["html"], str)
                  else list(cfg["html"]))
    if cfg["entry"] in html_names:
        html_names.remove(cfg["entry"])

    shared_refs: set[str] = set()
    for name, is_entry in [(cfg["entry"], True)] + [(n, False) for n in html_names]:
        raw = (src_dir / name).read_text(encoding="utf-8")
        shared_refs.update(_SHARED_REF.findall(raw))
        rel_out = "index.html" if is_entry else name
        out[rel_out] = _rewrite_html(raw, f"{cfg['folder']}/{name}", app, is_entry, cfg)

    for name in cfg["code"]:
        out[name] = _apply_patches((src_dir / name).read_text(encoding="utf-8"), app, name)

    for name in sorted(shared_refs):
        out[f"kit/{name}"] = (BUNDLE / "shared" / name).read_text(encoding="utf-8")

    out[".design-port-manifest.json"] = json.dumps({
        "tool": "scripts/port_full_design_to_web.py",
        "source": f"dist/sites/openharness-design/{cfg['folder']}",
        "entry": cfg["entry"],
        "generated": sorted(k for k in out if k != ".design-port-manifest.json"),
    }, indent=1) + "\n"
    return out


def port() -> int:
    for app in APPS:
        target = WEB / app
        target.mkdir(parents=True, exist_ok=True)
        files = generate(app)
        # lossless: a pre-existing hand-built front page is preserved, never overwritten away
        index = target / "index.html"
        if index.exists() and GENERATED_MARK not in index.read_text(encoding="utf-8", errors="replace"):
            legacy = target / "legacy.html"
            if not legacy.exists():
                index.rename(legacy)
                print(f"  [lossless] {app}: previous index.html preserved as legacy.html")
        for rel, content in files.items():
            dest = target / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")
        kit = sum(1 for k in files if k.startswith("kit/"))
        print(f"  [ported] {app}: {len(files)} files ({kit} kit, "
              f"{sum(1 for k in files if k.endswith('.html'))} html) ← {APPS[app]['folder']}/")
    print("PASS — full-design bundle ported into web/ (run --check anytime; see web/README.md)")
    return 0


def check() -> int:
    drift: list[str] = []
    for app in APPS:
        target = WEB / app
        for rel, content in generate(app).items():
            disk = target / rel
            if not disk.exists():
                drift.append(f"{app}/{rel}: MISSING (re-run the port script)")
            elif disk.read_text(encoding="utf-8") != content:
                drift.append(f"{app}/{rel}: DRIFTED from the generated transplant")
    if drift:
        print("FAIL — web/ full-design files drifted from dist/sites/openharness-design:")
        for d in drift:
            print("  ", d)
        print("Fix: edit the BUNDLE (or the port script) and re-run "
              "`python3 scripts/port_full_design_to_web.py` — never hand-edit generated copies.")
        return 1
    print("PASS — check_port_full_design_to_web: every generated web/ file matches the bundle "
          f"transplant byte-for-byte ({sum(len(generate(a)) for a in APPS)} files across {len(APPS)} apps).")
    return 0


def self_test() -> int:
    fails: list[str] = []

    def ck(name: str, ok: bool) -> None:
        print(f"  [{'ok' if ok else 'FAIL'}] {name}")
        if not ok:
            fails.append(name)

    with tempfile.TemporaryDirectory() as tmp:
        global WEB
        real_web, WEB = WEB, Path(tmp)
        try:
            port()
            for app, cfg in APPS.items():
                files = {p.relative_to(WEB / app).as_posix(): p for p in (WEB / app).rglob("*") if p.is_file()}
                entry = files["index.html"].read_text(encoding="utf-8")
                ck(f"{app}: entry generated + marked", GENERATED_MARK in entry)
                ck(f"{app}: no ../shared/ left in entry", "../shared/" not in entry)
                ck(f"{app}: vendored runtime (no unpkg)", "unpkg.com" not in entry)
                ck(f"{app}: service seams injected", "OHH_IDENTITY_BASE" in entry and "/registry" in entry)
                kit_ok = all((BUNDLE / "shared" / Path(rel).name).read_text(encoding="utf-8")
                             == p.read_text(encoding="utf-8")
                             for rel, p in files.items() if rel.startswith("kit/"))
                ck(f"{app}: kit byte-identical to bundle shared/", kit_ok)
                for name in cfg["code"]:
                    if name not in PATCHES.get(app, {}):
                        ck_ok = files[name].read_text(encoding="utf-8") == (
                            BUNDLE / cfg["folder"] / name).read_text(encoding="utf-8")
                        if not ck_ok:
                            ck(f"{app}: {name} verbatim", False)
            ck("harness-hub: live seam patches applied",
               "OHHLive.build(task)" in (WEB / "harness-hub" / "proto-pages-build.jsx").read_text(encoding="utf-8"))
            ck("harness-hub: ohh-live.js wired into the entry",
               'src="ohh-live.js"' in (WEB / "harness-hub" / "index.html").read_text(encoding="utf-8"))
            ck("baltor: guided demos ported",
               (WEB / "baltor" / "Baltor Guided Demos.html").exists()
               and 'href="index.html"' in (WEB / "baltor" / "Baltor Guided Demos.html").read_text(encoding="utf-8"))
            ck("context-is-everything: Demo Control Tower ported",
               (WEB / "context-is-everything" / "Demo Control Tower.html").exists())
        finally:
            WEB = real_web
    print("\n" + ("PASS — port_full_design_to_web self-test: deterministic transplant with verbatim kit, "
                  "recorded-only patches, seams, and lossless legacy handling."
                  if not fails else f"{len(fails)} FAILURES: {fails}"))
    return 0 if not fails else 1


if __name__ == "__main__":
    if "--self-test" in sys.argv:
        raise SystemExit(self_test())
    if "--check" in sys.argv:
        raise SystemExit(check())
    raise SystemExit(port())
